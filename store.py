"""Storage layer: originals on disk + a small SQLite index.

Layout under LECTO_STORE (default ./store):
    store.db                         series / chapters / pages index
    pages/<series>/<chapter>/NNN.jpg  normalized originals (max 1400 px wide)
    thumbs/<size>/<series>/<chapter>/NNN.webp   generated by thumbs.py
"""
import json
import os
import re
import sqlite3
import threading
import time

import collections_db as collections
import favs_db

ROOT = os.path.expanduser(os.environ.get('LECTO_STORE', './store'))
PAGES = os.path.join(ROOT, 'pages')
THUMBS = os.path.join(ROOT, 'thumbs')
DB = os.path.join(ROOT, 'store.db')

# Write lock de aplicacion: serializa las escrituras para que dos threads no
# compitan por el RESERVED lock de SQLite. En un HDD USB (btrfs, nodatacow) el
# fsync del commit es lento, y con BEGIN diferido dos transacciones que ambas
# leyeron (SHARED) y luego intentan escribir (RESERVED) causan "database is
# locked" cuando el perdedor excede el timeout. Las lecturas (WAL) no se ven
# afectadas: el lock solo envuelve escrituras.
_write_lock = threading.Lock()

ID = re.compile(r'^[a-z0-9][a-z0-9_-]{0,80}$')

SCHEMA = """
create table if not exists series(
  id text primary key, folder text not null, info text not null, added real);
create table if not exists chapters(
  series_id text not null, id text not null, number real, title text default '',
  source_file text, source_size integer, added real, primary key(series_id, id));
create table if not exists pages(
  series_id text not null, chapter_id text not null, n integer not null,
  w integer not null, h integer not null, bytes integer, primary key(series_id, chapter_id, n));
"""


_ready = set()   # databases whose schema this process already checked


def connect():
    """A connection per request. The schema is checked once per process: running the DDL on every
    connect took the write lock each time, and on a USB disk with btrfs that queued requests until
    "database is locked"."""
    os.makedirs(ROOT, exist_ok=True)
    c = sqlite3.connect(DB, timeout=30)
    c.row_factory = sqlite3.Row
    c.execute('pragma journal_mode=wal')
    c.execute('pragma synchronous=normal')   # WAL: safe against crashes, one fsync per checkpoint, not per commit
    if DB not in _ready:
        cols = [r[1] for r in c.execute('pragma table_info(series)')]
        if cols and 'info' not in cols:  # v1 table (title/rtl columns): rebuilt from info.json by the next ingest
            c.execute('drop table series')
        c.executescript(SCHEMA)
        collections.init(c)
        favs_db.init(c)
        _ready.add(DB)
    return c


def valid(*ids):
    return all(isinstance(i, str) and ID.match(i) for i in ids)


def page_path(sid, cid, n):
    return os.path.join(PAGES, sid, cid, f'{int(n):03d}.jpg')


def iter_pages(c):
    yield from c.execute('select series_id, chapter_id, n from pages order by series_id, chapter_id, n')


def catalog(c):
    """Shape the client reads. URLs are derived on the client from ids, so the
    catalog stays small and storage paths can change without touching it."""
    out = []
    for s in c.execute('select id, info from series'):
        info = json.loads(s['info'])
        chapters = []
        for ch in c.execute('select * from chapters where series_id=? order by number', (s['id'],)):
            dims = [[p['w'], p['h']] for p in c.execute(
                'select w, h from pages where series_id=? and chapter_id=? order by n', (s['id'], ch['id']))]
            chapters.append({'id': ch['id'], 'number': ch['number'], 'title': ch['title'] or '', 'pages': len(dims), 'dims': dims})
        if not chapters:
            continue
        cover = info.get('cover') or {'chapter': chapters[0]['id'], 'page': 1}
        out.append({k: info[k] for k in ('id', 'title', 'author', 'artist', 'description', 'genres', 'status', 'kind', 'language', 'source', 'reading')}
                   | {'cover': cover, 'chapters': chapters})
    return sorted(out, key=lambda x: x['title'].lower())


def series_folder(c, sid):
    row = c.execute('select folder from series where id=?', (sid,)).fetchone()
    return row['folder'] if row else None


def put_series(c, folder, info):
    with _write_lock, c:
        c.execute('insert into series(id, folder, info, added) values (?,?,?,strftime(\'%s\',\'now\')) '
                  'on conflict(id) do update set folder=excluded.folder, info=excluded.info',
                  (info['id'], folder, json.dumps(info, ensure_ascii=False)))


def stats(c):
    row = c.execute('select (select count(*) from series) s, (select count(*) from chapters) c, '
                    '(select count(*) from pages) p, (select coalesce(sum(bytes),0) from pages) b').fetchone()
    return {'series': row['s'], 'chapters': row['c'], 'pages': row['p'], 'originals_bytes': row['b'], 'at': time.time()}


def delete_chapter(c, sid, cid):
    """Remove a chapter for good: its source file in the library, its pages and thumbnails, its
    index rows and the favs that point at it. Returns False if there is no such chapter."""
    import shutil
    row = c.execute('select source_file from chapters where series_id=? and id=?', (sid, cid)).fetchone()
    if not row:
        return False
    folder = series_folder(c, sid)
    with _write_lock, c:
        c.execute('delete from pages where series_id=? and chapter_id=?', (sid, cid))
        c.execute('delete from chapters where series_id=? and id=?', (sid, cid))
        c.execute('delete from favs where series_id=? and chapter_id=?', (sid, cid))
    shutil.rmtree(os.path.join(PAGES, sid, cid), ignore_errors=True)
    for size in os.listdir(THUMBS) if os.path.isdir(THUMBS) else []:
        shutil.rmtree(os.path.join(THUMBS, size, sid, cid), ignore_errors=True)
    if folder and row['source_file']:
        try:
            os.remove(os.path.join(folder, row['source_file']))
        except OSError:
            pass   # read-only library: the chapter is gone from Lecto, the file stays
    return True

